import * as fs from 'node:fs';
import * as path from 'node:path';
import type { Finding } from './types.js';
import { VERSION } from './version.js';

const TEST_TIMEOUT_MS = 30_000;

function json(value: unknown): string {
  return JSON.stringify(value);
}

/**
 * Generates a self-contained Playwright spec that reproduces one verified
 * finding. The assertion expects the fault to still be PRESENT: while the bug
 * exists the test passes, which proves stable reproduction; after a fix the
 * test fails and points the developer to the "fixed" assertion to swap in.
 */
function specFor(
  finding: Finding,
  viewports: { desktop: { width: number; height: number }; mobile: { width: number; height: number } }
): string {
  const plan = finding.plan;
  const header = [
    `import { test, expect } from '@playwright/test';`,
    ``,
    `// Generated by ReproCase v${VERSION}.`,
    `// Finding: ${finding.id} — ${finding.title}`,
    `// Status: ${finding.status}, reproduced ${finding.repro.successes}/${finding.repro.attempts} times during verification.`,
    `//`,
    `// This is a REPRODUCTION test: it asserts that the fault is still present.`,
    `// It passes while the bug exists and starts failing once the bug is fixed.`,
    `// When that happens, replace the assertion with the commented-out`,
    `// "after fix" expectation in this file to keep it as a regression guard.`,
    ``
  ].join('\n');

  if (plan.kind === 'js-error' || plan.kind === 'console-error') {
    const clicks = (plan.steps ?? [])
      .filter((s) => s.action === 'click' && s.selector)
      .map((s) => `  await page.click(${json(s.selector!)});`)
      .join('\n');
    const needle = (plan.message ?? '').trim().slice(0, 120);
    return [
      header,
      `test('reproduces ${finding.id}: ${finding.title.replace(/['\\]/g, ' ').slice(0, 100)}', async ({ page }) => {`,
      `  test.setTimeout(${TEST_TIMEOUT_MS});`,
      `  const errors: string[] = [];`,
      `  page.on('pageerror', (err) => errors.push(String(err?.message ?? err)));`,
      `  page.on('console', (msg) => { if (msg.type() === 'error') errors.push(msg.text()); });`,
      `  await page.goto(${json(plan.url)}, { waitUntil: 'load' });`,
      clicks,
      `  await page.waitForTimeout(800);`,
      `  // Original fault signature: ${json(needle || '(any error)')}`,
      `  const reproduced = errors.some((m) => m.includes(${json(needle)}));`,
      `  expect(reproduced, 'Expected the original fault to still reproduce. If this fails, the bug may be fixed — swap in the regression assertion.').toBe(true);`,
      `  // After fixing the bug, assert correctness instead:`,
      `  // expect(errors, 'page must stay free of JS errors').toEqual([]);`,
      `});`,
      ``
    ]
      .filter((l) => l !== undefined)
      .join('\n');
  }

  if (plan.kind === 'overflow') {
    const usedViewport = plan.viewport === 'mobile' ? viewports.mobile : viewports.desktop;
    return [
      header,
      `test.use({ viewport: { width: ${usedViewport.width}, height: ${usedViewport.height} } });`,
      ``,
      `test('reproduces ${finding.id}: ${finding.title.replace(/['\\]/g, ' ').slice(0, 100)}', async ({ page }) => {`,
      `  test.setTimeout(${TEST_TIMEOUT_MS});`,
      `  await page.goto(${json(plan.url)}, { waitUntil: 'load' });`,
      `  await page.waitForTimeout(300);`,
      `  const m = await page.evaluate(() => ({`,
      `    clientWidth: document.documentElement.clientWidth,`,
      `    scrollWidth: Math.max(document.documentElement.scrollWidth, document.body ? document.body.scrollWidth : 0)`,
      `  }));`,
      `  expect(m.scrollWidth - m.clientWidth, 'Expected horizontal overflow to still reproduce. If this fails, the bug may be fixed — swap in the regression assertion.').toBeGreaterThan(2);`,
      `  // After fixing the bug, assert correctness instead:`,
      `  // expect(m.scrollWidth - m.clientWidth, 'no horizontal overflow allowed').toBeLessThanOrEqual(2);`,
      `});`,
      ``
    ].join('\n');
  }

  // goto-status | link-status | resource-status | resource-request-error
  if (plan.kind === 'resource-request-error') {
    return [
      header,
      `test('reproduces ${finding.id}: ${finding.title.replace(/['\\]/g, ' ').slice(0, 100)}', async ({ page }) => {`,
      `  test.setTimeout(${TEST_TIMEOUT_MS});`,
      `  const failed: string[] = [];`,
      `  page.on('requestfailed', (req) => failed.push(req.url()));`,
      `  await page.goto(${json(plan.url)}, { waitUntil: 'load' });`,
      `  await page.waitForTimeout(500);`,
      `  expect(failed.some((u) => u === ${json(plan.targetUrl ?? '')}), 'Expected the resource request to still fail. If this fails, the bug may be fixed — swap in the regression assertion.').toBe(true);`,
      `});`,
      ``
    ].join('\n');
  }

  const target = plan.targetUrl ?? plan.url;
  return [
    header,
    `test('reproduces ${finding.id}: ${finding.title.replace(/['\\]/g, ' ').slice(0, 100)}', async ({ page }) => {`,
    `  test.setTimeout(${TEST_TIMEOUT_MS});`,
    `  let failed = false;`,
    `  try {`,
    `    const resp = await page.goto(${json(target)}, { waitUntil: 'load' });`,
    `    failed = resp ? resp.status() >= 400 : true;`,
    `  } catch {`,
    `    failed = true;`,
    `  }`,
    `  expect(failed, 'Expected the original load failure to still reproduce. If this fails, the bug may be fixed — swap in the regression assertion.').toBe(true);`,
    `  // After fixing the bug, assert correctness instead:`,
    `  // const resp = await page.goto(${json(target)});`,
    `  // expect(resp.ok(), 'must load without error').toBe(true);`,
    `});`,
    ``
  ].join('\n');
}

const PLAYWRIGHT_CONFIG = [
  `// Generated by ReproCase. The specs in this folder use absolute URLs`,
  `// recorded during the scan, so the site under test must be reachable.`,
  `// Run:  npx playwright test --config playwright.config.mjs`,
  `export default {`,
  `  testDir: '.',`,
  `  timeout: ${TEST_TIMEOUT_MS},`,
  `  use: { headless: true },`,
  `  reporter: [['list']]`,
  `};`,
  ``
].join('\n');

const GENERATED_README = (count: number): string =>
  [
    `# Generated reproduction tests`,
    ``,
    `ReproCase generated ${count} Playwright spec(s) from verified findings of one scan.`,
    ``,
    `## Run them`,
    ``,
    '```bash',
    `# 1. Start the site that was scanned (the specs use absolute URLs).`,
    `# 2. From this folder, with @playwright/test installed somewhere up the tree:`,
    `npx playwright test --config playwright.config.mjs`,
    '```',
    ``,
    `## What the assertions mean`,
    ``,
    `Each spec asserts that the original fault is STILL PRESENT (a reproduction test).`,
    `It passes while the bug exists and fails once you fix it — that failure is the`,
    `signal to swap in the commented-out "after fix" assertion, turning the file into`,
    `a permanent regression guard.`,
    ``
  ].join('\n');

/**
 * Writes one spec per verified finding plus a ready-to-run Playwright config.
 * Returns the artifact-relative paths of generated files.
 */
export function generateTests(
  findings: Finding[],
  outDir: string,
  viewports: { desktop: { width: number; height: number }; mobile: { width: number; height: number } }
): string[] {
  const dir = path.join(outDir, 'generated-tests');
  fs.mkdirSync(dir, { recursive: true });
  const files: string[] = [];
  const verified = findings.filter((f) => f.status === 'verified');

  verified.forEach((f, i) => {
    const name = `reprocase-${f.id}-${String(i + 1).padStart(2, '0')}.spec.ts`;
    fs.writeFileSync(path.join(dir, name), specFor(f, viewports), 'utf8');
    f.generatedTest = `generated-tests/${name}`;
    files.push(`generated-tests/${name}`);
  });

  fs.writeFileSync(path.join(dir, 'playwright.config.mjs'), PLAYWRIGHT_CONFIG, 'utf8');
  fs.writeFileSync(path.join(dir, 'README.md'), GENERATED_README(verified.length), 'utf8');
  files.push('generated-tests/playwright.config.mjs', 'generated-tests/README.md');
  return files;
}
